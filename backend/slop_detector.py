"""Measure code-quality problems that can be seen statically.

The detector does not label code as AI-generated. It reports duplicate blocks,
duplicate function bodies, duplicate imports, commented-out code, very branchy
functions, and placeholder-style names.
"""

from __future__ import annotations

import ast
import re
from collections import defaultdict

from backend.config import COMPLEXITY_THRESHOLD, DUPLICATE_WINDOW
from backend.models import Finding, make_finding
from backend.python_ast import (
    branch_complexity,
    is_abstract_function,
    is_placeholder_function,
    iter_functions,
    parse_module,
)
from backend.repository_analyzer import RepoSnapshot, SourceFile, line_snippet

BAD_FUNCTION_NAMES = {"foo", "bar", "baz", "tmp", "temp", "stuff", "thing", "asdf", "xxx", "var", "obj"}
_PY_COMMENT = re.compile(r"^\s*#\s*(def |class |import |from |return |if |for |while |try:|with |else:)")
_C_COMMENT = re.compile(r"^\s*//\s*(function |return |if |for |while |class |import |const |let |var )")


def _normalize(source: SourceFile) -> list[tuple[int, str]]:
    normalized: list[tuple[int, str]] = []
    for number, line in enumerate(source.lines, start=1):
        text = line.strip()
        if source.language == "Python":
            if not text or text.startswith("#"):
                continue
            text = re.sub(r"\s+#.*$", "", text)
        else:
            if not text or text.startswith("//") or text.startswith("/*") or text.startswith("*"):
                continue
            text = re.sub(r"\s+//.*$", "", text)
        text = re.sub(r"\s+", " ", text).strip()
        if not text or text in {"{", "}", "pass", "..."}:
            continue
        normalized.append((number, text))
    return normalized


def _duplicate_blocks(files: list[SourceFile]) -> list[Finding]:
    index: dict[tuple[str, ...], tuple[str, int]] = {}
    reported: set[tuple[str, str, int, int]] = set()
    findings: list[Finding] = []
    for source in files:
        normalized = _normalize(source)
        if len(normalized) < DUPLICATE_WINDOW:
            continue
        for offset in range(0, len(normalized) - DUPLICATE_WINDOW + 1):
            window = normalized[offset : offset + DUPLICATE_WINDOW]
            if sum(len(text) for _, text in window) < 24:
                continue
            key = tuple(text for _, text in window)
            start = window[0][0]
            if key in index:
                previous_file, previous_line = index[key]
                if previous_file == source.relative and abs(previous_line - start) < DUPLICATE_WINDOW:
                    continue
                bucket = tuple(sorted((previous_file, source.relative))) + (previous_line // 4, start // 4)
                if bucket in reported:
                    continue
                reported.add(bucket)
                findings.append(
                    make_finding(
                        rule_id="duplicate-block",
                        category="slop",
                        severity="low",
                        title="Repeated code block",
                        description=(
                            f"These {DUPLICATE_WINDOW} lines also appear in {previous_file} near line {previous_line}. "
                            "Repeated blocks are a maintenance risk. This is not a claim that the code was generated by a model."
                        ),
                        file=source.relative,
                        line=start,
                        end_line=window[-1][0],
                        recommendation="Extract the shared behavior into one function, or delete the copy that is no longer needed.",
                        snippet=line_snippet(source.lines, start, radius=DUPLICATE_WINDOW),
                    )
                )
            else:
                index[key] = (source.relative, start)
    return findings


def _function_fingerprint(fn: ast.AST) -> str | None:
    if is_placeholder_function(fn):
        return None
    body = list(getattr(fn, "body", []))
    if body and isinstance(body[0], ast.Expr) and isinstance(getattr(body[0], "value", None), ast.Constant):
        if isinstance(body[0].value.value, str):
            body = body[1:]
    if len(body) < 3:
        return None
    module = ast.Module(body=body, type_ignores=[])
    return ast.dump(module, include_attributes=False)


def _python_structure(source: SourceFile) -> list[Finding]:
    tree = parse_module(source.text)
    if tree is None:
        return []
    findings: list[Finding] = []
    functions = iter_functions(tree)

    groups: dict[str, list[ast.AST]] = defaultdict(list)
    for fn, class_node in functions:
        if class_node is not None or is_abstract_function(fn, class_node):
            continue
        fingerprint = _function_fingerprint(fn)
        if fingerprint:
            groups[fingerprint].append(fn)
    for copies in groups.values():
        if len(copies) < 2:
            continue
        original = copies[0]
        duplicate = copies[1]
        findings.append(
            make_finding(
                rule_id="duplicate-function",
                category="slop",
                severity="medium",
                title="Duplicate function implementation",
                description=(
                    f"`{getattr(duplicate, 'name', 'function')}` has the same body as "
                    f"`{getattr(original, 'name', 'function')}` at line {getattr(original, 'lineno', 1)}. "
                    "The implementations can drift apart."
                ),
                file=source.relative,
                line=int(getattr(duplicate, "lineno", 1)),
                recommendation="Keep one implementation and call it from both places.",
                snippet=line_snippet(source.lines, int(getattr(duplicate, "lineno", 1))),
            )
        )

    imports: dict[str, list[int]] = defaultdict(list)
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                imports[alias.name].append(node.lineno)
        elif isinstance(node, ast.ImportFrom):
            module = node.module or ""
            for alias in node.names:
                imports[f"{module}:{alias.name}"].append(node.lineno)
    for name, lines in imports.items():
        unique_lines = sorted(set(lines))
        if len(unique_lines) < 2:
            continue
        findings.append(
            make_finding(
                rule_id="duplicate-import",
                category="slop",
                severity="low",
                title="Duplicate import",
                description=f"`{name}` is imported more than once in this file.",
                file=source.relative,
                line=unique_lines[1],
                recommendation="Keep a single import at the top of the module.",
                snippet=line_snippet(source.lines, unique_lines[1]),
            )
        )

    for fn, class_node in functions:
        if is_abstract_function(fn, class_node) or is_placeholder_function(fn):
            continue
        name = getattr(fn, "name", "")
        if name.lower() in BAD_FUNCTION_NAMES or re.fullmatch(r"[a-z]", name):
            findings.append(
                make_finding(
                    rule_id="poor-name",
                    category="slop",
                    severity="low",
                    title="Unclear function name",
                    description=(
                        f"`{name}` does not describe what the function does. "
                        "A short or joke name makes the surrounding code harder to review."
                    ),
                    file=source.relative,
                    line=int(getattr(fn, "lineno", 1)),
                    recommendation="Rename the function after its result or side effect.",
                    snippet=line_snippet(source.lines, int(getattr(fn, "lineno", 1))),
                )
            )
        complexity = branch_complexity(fn)
        if complexity >= COMPLEXITY_THRESHOLD:
            findings.append(
                make_finding(
                    rule_id="high-complexity",
                    category="slop",
                    severity="medium",
                    title="Excessively branched function",
                    description=(
                        f"`{name}` has a simplified branch count of {complexity}. "
                        f"The project threshold is {COMPLEXITY_THRESHOLD}. This measures branching, not whether a model wrote it."
                    ),
                    file=source.relative,
                    line=int(getattr(fn, "lineno", 1)),
                    recommendation="Split the branches into named helpers or a table lookup.",
                    snippet=line_snippet(source.lines, int(getattr(fn, "lineno", 1))),
                )
            )
    return findings


def _commented_out(source: SourceFile) -> list[Finding]:
    pattern = _PY_COMMENT if source.language == "Python" else _C_COMMENT
    run: list[int] = []
    findings: list[Finding] = []

    def close() -> None:
        nonlocal run
        if len(run) >= 3:
            findings.append(
                make_finding(
                    rule_id="commented-out-code",
                    category="slop",
                    severity="low",
                    title="Commented-out code",
                    description="Several consecutive comments look like disabled code rather than an explanation.",
                    file=source.relative,
                    line=run[0],
                    end_line=run[-1],
                    recommendation="Delete the dead code or restore it through version control if it is still needed.",
                    snippet=line_snippet(source.lines, run[0], radius=3),
                )
            )
        run = []

    for number, line in enumerate(source.lines, start=1):
        if pattern.match(line):
            run.append(number)
        else:
            close()
    close()
    return findings


def detect_slop(snapshot: RepoSnapshot) -> list[Finding]:
    files = snapshot.code_files(include_tests=False)
    findings = _duplicate_blocks(files)
    for source in files:
        if source.language == "Python":
            findings.extend(_python_structure(source))
        findings.extend(_commented_out(source))
    return findings
